package com.mardous.booming.data.remote.lyrics.api.unison

import android.content.SharedPreferences
import com.mardous.booming.data.model.Song
import com.mardous.booming.data.model.lyrics.RawLyrics
import com.mardous.booming.data.remote.RateLimiter
import com.mardous.booming.data.remote.lyrics.api.LyricsApi
import com.mardous.booming.data.remote.lyrics.api.LyricsProvider
import com.mardous.booming.data.remote.lyrics.model.UnisonResponse
import com.mardous.booming.util.Constants.SIMPLE_USER_AGENT
import io.ktor.client.HttpClient
import io.ktor.client.call.body
import io.ktor.client.plugins.timeout
import io.ktor.client.request.get
import io.ktor.client.request.header
import io.ktor.client.request.parameter
import io.ktor.client.request.userAgent
import io.ktor.http.HttpStatusCode

/**
 * Unison community lyrics (unison.betterlyrics.org). Returns rich-synced
 * TTML, line-synced LRC or plain text, authenticated with the per-device
 * keyId generated by [UnisonKeyProvider].
 */
class UnisonApi(private val client: HttpClient, preferences: SharedPreferences) : LyricsApi {

    override val provider = LyricsProvider.Unison

    private val rateLimiter = RateLimiter("UnisonApi")
    private val keyProvider = UnisonKeyProvider(preferences)

    override suspend fun downloadLyrics(
        song: Song,
        title: String,
        artist: String
    ): RawLyrics.Remote? {
        if (rateLimiter.isRateLimited) return null

        val keyId = try {
            keyProvider.getKeyId()
        } catch (_: Exception) {
            return null
        }

        val response = client.get(UNISON_API_URL) {
            userAgent(SIMPLE_USER_AGENT)
            header("x-key-id", keyId)
            parameter("song", title)
            parameter("artist", artist)
            parameter("duration", (song.duration / 1000))
            if (song.albumName.isNotBlank()) parameter("album", song.albumName)
            timeout {
                connectTimeoutMillis = 5000
                socketTimeoutMillis = 10000
                requestTimeoutMillis = 15000
            }
        }

        if (rateLimiter.handleResponse(response)) return null
        if (response.status != HttpStatusCode.OK) return null

        val data = response.body<UnisonResponse>().data ?: return null
        val lyrics = data.lyrics?.takeIf { it.isNotBlank() } ?: return null
        val content = RawLyrics.Remote.Content(provider.displayName, lyrics)
        return when (data.format?.lowercase()) {
            "ttml", "lrc" -> RawLyrics.Remote(synced = content)
            "plain" -> RawLyrics.Remote(plain = content)
            else -> if (lyrics.contains("<tt") || lyrics.contains("[00:")) {
                RawLyrics.Remote(synced = content)
            } else {
                RawLyrics.Remote(plain = content)
            }
        }
    }

    companion object {
        private const val UNISON_API_URL = "https://unison.betterlyrics.org/lyrics"
    }
}
