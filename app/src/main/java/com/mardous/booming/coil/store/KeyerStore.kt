package com.mardous.booming.coil.store

import coil3.key.Keyer
import coil3.request.Options
import com.mardous.booming.coil.CustomArtistImageManager
import com.mardous.booming.coil.model.ArtistImage
import com.mardous.booming.coil.model.AudioCover
import com.mardous.booming.coil.model.AutoGeneratedImage
import com.mardous.booming.coil.model.PlaylistImage
import com.mardous.booming.data.model.network.NetworkFeature

class AudioCoverKeyer : Keyer<AudioCover> {
    override fun key(data: AudioCover, options: Options): String? {
        return buildString {
            if (data.isAlbum) {
                append("album::")
            } else {
                append("song::")
            }
            append("albumId=").append(data.albumId)
            append("|uri=").append(data.uri.toString())
            append("|path=").append(data.path)
            append("|folderArt=").append(data.isUseFolderArt)
            append("|lastModified=").append(data.lastModified)
        }
    }
}

class ArtistImageKeyer(
    private val customArtistImageManager: CustomArtistImageManager
) : Keyer<ArtistImage> {
    override fun key(data: ArtistImage, options: Options): String? {
        val hasCustomImage = customArtistImageManager.hasCustomImage(data)
        val signature = customArtistImageManager.getSignature(data)
        val onlineEnabled = NetworkFeature.Images.Artists.isEnabled
        val idKey = if (data.isAlbumArtist) "" else "id=${data.id}|"
        return "artist::${idKey}name=${data.name}|coverUri=${data.coverUri}|hasCustomImage=$hasCustomImage|signature=$signature|online=$onlineEnabled"
    }
}

class PlaylistImageKeyer : Keyer<PlaylistImage> {
    override fun key(data: PlaylistImage, options: Options): String? {
        // The collage is built from the first 4 songs with distinct
        // albums, so the key must change only when THOSE candidates
        // change. The old song-count key invalidated the cover on every
        // add/remove — even when the visible tiles were untouched —
        // forcing a full collage regeneration per add; a regeneration
        // that failed (art not scanned yet, decode hiccup) left the
        // default icon in place and, with the count stable again, was
        // never retried. Keying on the tile identities keeps the cached
        // collage whenever the add doesn't affect it.
        val tiles = data.songs.distinctBy { it.albumId }.take(4)
        return buildString {
            append("playlist3::id=").append(data.playlistEntity.playListId)
            append("|customCoverUri=").append(data.playlistEntity.customCoverUri)
            tiles.forEach { song ->
                append("|tile=").append(song.albumId)
                .append(':').append(song.data.hashCode())
                .append(':').append(song.rawDateModified)
            }
        }
    }
}

class AutoGeneratedImageKeyer : Keyer<AutoGeneratedImage> {
    override fun key(
        data: AutoGeneratedImage,
        options: Options
    ): String? {
        return "auto-generated::type=${data.type}|id=${data.id}|songCount=${data.songCount}"
    }
}