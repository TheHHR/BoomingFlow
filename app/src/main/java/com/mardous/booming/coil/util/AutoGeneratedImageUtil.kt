package com.mardous.booming.coil.util

import android.content.Context
import android.content.SharedPreferences
import android.graphics.Bitmap
import coil3.Image
import coil3.SingletonImageLoader
import coil3.asImage
import coil3.request.ImageRequest
import coil3.request.transformations
import coil3.size.Precision
import coil3.toBitmap
import coil3.transform.RoundedCornersTransformation
import com.mardous.booming.coil.model.AudioCover
import com.mardous.booming.data.model.Song
import com.mardous.booming.extensions.media.albumArtistName
import com.mardous.booming.util.USE_FOLDER_ART
import org.koin.core.component.KoinComponent
import org.koin.core.component.inject

object AutoGeneratedImageUtil : KoinComponent {

    private val preferences: SharedPreferences by inject()

    suspend fun getPlaylistImage(context: Context, songs: List<Song>): Image? {
        if (songs.isEmpty()) return null
        val bitmaps = songs.distinctBy { it.albumId }.take(4).mapNotNull {
            getBitmapForSong(
                context,
                it,
                size = 800,
                memoryCacheKey = tileCacheKey(it)
            )
        }
        if (bitmaps.isEmpty()) return null
        val bitmap = if (bitmaps.size > 1) {
            MergedImageUtils.joinImages2x2(bitmaps) ?: return null
        } else {
            bitmaps[0]
        }
        return bitmap.asImage()
    }

    suspend fun getImage(context: Context, songs: List<Song>): Image? {
        val bitmap = if (songs.size > 1) {
            MergedImageUtils.joinImages(
                songs.distinctBy { it.albumId }.take(9).mapNotNull {
                    getBitmapForSong(
                        context,
                        it,
                        size = 200,
                        memoryCacheKey = tileCacheKey(it),
                        roundedCorner = true
                    )
                }
            )
        } else if (songs.size == 1) {
            getBitmapForSong(
                context,
                songs[0],
                size = 200,
                memoryCacheKey = tileCacheKey(songs[0])
            )
        } else {
            null
        }
        return bitmap?.asImage()
    }

    private fun tileCacheKey(song: Song): String {
        return "playlist-preview-tile::album=${song.albumId}" +
                "|path=${song.data}" +
                "|mod=${song.rawDateModified}"
    }

    private suspend fun getBitmapForSong(
        context: Context,
        song: Song,
        size: Int,
        memoryCacheKey: String,
        roundedCorner: Boolean = false
    ): Bitmap? {
        return try {
            val cover = AudioCover(
                albumId = song.albumId,
                uri = song.uri,
                path = song.data,
                artistName = song.albumArtistName(),
                albumName = song.albumName,
                title = song.title,
                lastModified = song.rawDateModified,
                isIgnoreMediaStore = true,
                isUseFolderArt = preferences.getBoolean(USE_FOLDER_ART, false),
                isAlbum = true
            )
            val request = ImageRequest.Builder(context)
                .data(cover)
                .memoryCacheKey(memoryCacheKey)
                .precision(Precision.EXACT)
                .size(size)
            if (roundedCorner) {
                request.transformations(RoundedCornersTransformation(20f))
            }
            val result = SingletonImageLoader.get(context).execute(request.build())
            result.image?.toBitmap()
        } catch (_: Exception) {
            null
        }
    }
}
